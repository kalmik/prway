// Noise filter: marks files that don't need a careful read, without any AI.
//   repo-rule       matches a "skip" pattern in the repo's .prway.json
//   generated       lockfiles, build output, minified files, snapshots, and files the repo marks
//                   with `linguist-generated` in .gitattributes
//   rename-only     moved or renamed with no content change (or only whitespace changes)
//   formatting-only the diff disappears when whitespace and blank lines are ignored, or both
//                   versions have the same code tokens (line wrapping, quote style, trailing commas)
//   moved           every changed line is code git sees as moved (git diff --color-moved)

import { posix } from 'node:path'
import type { ChangedFile, NoiseKind, SideLines } from '../../shared/types'

const LOCKFILES = new Set([
  'package-lock.json',
  'npm-shrinkwrap.json',
  'yarn.lock',
  'pnpm-lock.yaml',
  'bun.lock',
  'bun.lockb',
  'Cargo.lock',
  'poetry.lock',
  'Pipfile.lock',
  'uv.lock',
  'composer.lock',
  'Gemfile.lock',
  'go.sum',
  'packages.lock.json',
  'Podfile.lock',
  'pubspec.lock',
  'mix.lock',
  'flake.lock'
])

const GENERATED_DIRS = ['dist/', 'build/', 'vendor/', 'node_modules/', '__snapshots__/', '__generated__/', 'generated/']

const GENERATED_SUFFIXES = [
  '.min.js',
  '.min.css',
  '.map',
  '.snap',
  '.pb.go',
  '_pb2.py',
  '_pb2_grpc.py',
  '.g.dart',
  '.freezed.dart',
  '.designer.cs',
  '.generated.ts',
  '.generated.cs'
]

/** Returns why a path looks generated, or null. */
export function generatedReason(path: string): string | null {
  const name = path.split('/').pop() ?? path
  if (LOCKFILES.has(name)) return 'Lockfile'
  const lower = path.toLowerCase()
  const dir = GENERATED_DIRS.find((d) => lower.startsWith(d) || lower.includes(`/${d}`))
  if (dir) return `Inside ${dir.slice(0, -1)}/`
  const suffix = GENERATED_SUFFIXES.find((s) => lower.endsWith(s))
  if (suffix) return `Generated file (${suffix})`
  return null
}

export interface NumstatEntry {
  path: string
  additions: number | null
  deletions: number | null
}

/** Parses `git diff --numstat -z -M`. Renames come as "a\td\t\0old\0new\0". */
export function parseNumstat(out: string): Map<string, NumstatEntry> {
  const parts = out.split('\0')
  const result = new Map<string, NumstatEntry>()
  for (let i = 0; i < parts.length; i++) {
    const m = /^(-|\d+)\t(-|\d+)\t(.*)$/.exec(parts[i])
    if (!m) continue
    let path = m[3]
    if (path === '') {
      i += 2 // skip old path, take new path
      path = parts[i]
    }
    const num = (s: string) => (s === '-' ? null : Number(s))
    result.set(path, { path, additions: num(m[1]), deletions: num(m[2]) })
  }
  return result
}

/** Parses `git check-attr -z linguist-generated` output: "path\0attr\0value\0" triples. */
export function parseCheckAttr(out: string): Set<string> {
  const parts = out.split('\0')
  const generated = new Set<string>()
  for (let i = 0; i + 2 < parts.length; i += 3) {
    if (parts[i + 2] === 'true' || parts[i + 2] === 'set') generated.add(parts[i])
  }
  return generated
}

// ---- Per-repo rules (.prway.json) ----

/**
 * .prway.json at the repo root, read from the PR's base so a PR cannot hide its own changes:
 *   {
 *     "skip": ["priv/gettext/**", { "path": "schema.graphql", "reason": "Generated by Absinthe" }],
 *     "review": ["mix.lock"],                  // never treated as noise, even if built-in rules say so
 *     "domains": { "lib/app/billing/**": "billing" }   // knowledge base grouping
 *   }
 */
export interface RepoRules {
  skip: { path: string; reason: string }[]
  review: string[]
  domains: { path: string; domain: string }[]
  /** Globs of entry points (controllers, workers…) where tracing callers stops; added to PRway's defaults. */
  entryPoints?: string[]
  /** The team's prompt customisation ("prompts" in .prway.json), parsed by promptLayers.ts. */
  prompts?: unknown
}

export const EMPTY_RULES: RepoRules = { skip: [], review: [], domains: [] }

/** Parses .prway.json. Throws a readable error when the file is not valid. */
export function parseRepoRules(text: string): RepoRules {
  const raw = JSON.parse(text) as Record<string, unknown>
  const strings = (v: unknown): string[] => (Array.isArray(v) ? v.filter((x): x is string => typeof x === 'string') : [])
  const skip = (Array.isArray(raw.skip) ? raw.skip : []).flatMap((s): RepoRules['skip'] => {
    if (typeof s === 'string') return [{ path: s, reason: 'Skipped by .prway.json' }]
    if (s && typeof s === 'object' && typeof (s as { path?: unknown }).path === 'string') {
      const { path, reason } = s as { path: string; reason?: unknown }
      return [{ path, reason: typeof reason === 'string' ? `${reason} (.prway.json)` : 'Skipped by .prway.json' }]
    }
    return []
  })
  const domains =
    raw.domains && typeof raw.domains === 'object'
      ? Object.entries(raw.domains as Record<string, unknown>)
          .filter((e): e is [string, string] => typeof e[1] === 'string')
          .map(([path, domain]) => ({ path, domain }))
      : []
  return { skip, review: strings(raw.review), domains, entryPoints: strings(raw.entryPoints), prompts: raw.prompts }
}

/** Glob match: `**` any depth, `*` within one folder, `?` one character. A pattern without "/" matches the file name anywhere. */
export function matchGlob(path: string, pattern: string): boolean {
  const p = pattern.replace(/^\.?\//, '')
  if (!p.includes('/')) return posix.matchesGlob(path.split('/').pop() ?? path, p) || posix.matchesGlob(path, `**/${p}`)
  return posix.matchesGlob(path, p) || (p.endsWith('/') && path.startsWith(p))
}

// ---- Moved code (git diff --color-moved) ----

/** Colors PRway asks git to use, so moved lines can be told apart from plain added/removed lines. */
export const MOVED_COLOR_CONFIG = [
  'color.diff.old=red',
  'color.diff.new=green',
  'color.diff.oldMoved=magenta',
  'color.diff.newMoved=cyan',
  'color.diff.oldMovedAlternative=magenta',
  'color.diff.newMovedAlternative=cyan',
  'color.diff.oldMovedDimmed=magenta',
  'color.diff.newMovedDimmed=cyan',
  'color.diff.oldMovedAlternativeDimmed=magenta',
  'color.diff.newMovedAlternativeDimmed=cyan',
  'core.quotePath=false'
]

export interface MovedStat extends SideLines {
  added: number
  deleted: number
}

const ANSI = /\x1b\[[0-9;]*m/g

/** Parses `git diff --color=always --color-moved` output into moved line numbers per file (new path). */
export function parseMovedDiff(out: string): Map<string, MovedStat> {
  const result = new Map<string, MovedStat>()
  let cur: MovedStat | null = null
  let oldPath = ''
  let oldLine = 0
  let newLine = 0
  for (const raw of out.split('\n')) {
    const line = raw.replace(ANSI, '')
    if (line.startsWith('diff --git ')) {
      cur = null
      continue
    }
    if (line.startsWith('--- ')) {
      oldPath = line.slice(4).replace(/^a\//, '')
      continue
    }
    if (line.startsWith('+++ ')) {
      const p = line.slice(4) === '/dev/null' ? oldPath : line.slice(4).replace(/^b\//, '')
      cur = { left: [], right: [], added: 0, deleted: 0 }
      result.set(p.replace(/\t$/, ''), cur)
      continue
    }
    const hunk = /^@@ -(\d+)(?:,\d+)? \+(\d+)(?:,\d+)? @@/.exec(line)
    if (hunk) {
      oldLine = Number(hunk[1])
      newLine = Number(hunk[2])
      continue
    }
    if (!cur) continue
    const moved = raw.startsWith('\x1b[35m') || raw.startsWith('\x1b[36m') || /^\x1b\[[0-9;]*(35|36)m/.test(raw)
    if (line.startsWith('+')) {
      cur.added++
      if (moved) cur.right.push(newLine)
      newLine++
    } else if (line.startsWith('-')) {
      cur.deleted++
      if (moved) cur.left.push(oldLine)
      oldLine++
    } else if (line.startsWith(' ')) {
      oldLine++
      newLine++
    }
  }
  return result
}

// ---- Same code tokens (formatting beyond whitespace) ----

/** Languages where whitespace or indentation changes meaning: never compared by tokens. */
const WHITESPACE_SENSITIVE = /\.(py|pyi|ya?ml|md|markdown|mdx|haml|slim|pug|jade|coffee|nim|hs|elm|fs|fsx|mk|txt|rst|csv|tsv)$|(^|\/)(Makefile|Dockerfile)$/i
const JS_LIKE = /\.(m?[jt]sx?|cjs|cts|mts|json|jsonc|css|scss|less|vue|svelte)$/i
/** Languages whose ' and " strings mean the same thing. */
const SAME_QUOTES = /\.(m?[jt]sx?|cjs|cts|mts|css|scss|less|vue|svelte|php)$/i

export function tokenComparable(path: string): boolean {
  return !WHITESPACE_SENSITIVE.test(path)
}

/**
 * The code with formatting removed: whitespace outside strings is dropped (or kept as one space
 * between two words), and for JS-like files quote style, semicolons and trailing commas are ignored.
 */
export function canonicalCode(text: string, path: string): string {
  const jsLike = JS_LIKE.test(path)
  const sameQuotes = SAME_QUOTES.test(path)
  const out: string[] = []
  let pendingSpace = false
  const word = (c: string | undefined) => !!c && /[\w$@]/.test(c)
  const push = (tok: string) => {
    if (pendingSpace && word(out.at(-1)?.at(-1)) && word(tok[0])) out.push(' ')
    pendingSpace = false
    out.push(tok)
  }
  for (let i = 0; i < text.length; ) {
    const c = text[i]
    if (/\s/.test(c)) {
      pendingSpace = true
      i++
      continue
    }
    if (c === '"' || c === "'" || c === '`') {
      let j = i + 1
      while (j < text.length && text[j] !== c) j += text[j] === '\\' ? 2 : 1
      let body = text.slice(i + 1, j)
      let q = c
      if (sameQuotes && c !== '`' && !body.includes('"') && !body.includes("'")) q = '"'
      push(q + body + q)
      i = j + 1
      continue
    }
    if (jsLike && c === ';') {
      pendingSpace = true
      i++
      continue
    }
    if (jsLike && c === ',') {
      // Trailing comma: the next non-space character closes a bracket.
      let j = i + 1
      while (j < text.length && /\s/.test(text[j])) j++
      if (/[)\]}]/.test(text[j] ?? '')) {
        i++
        continue
      }
    }
    push(c)
    i++
  }
  return out.join('')
}

export interface NoiseInput {
  files: (Omit<ChangedFile, 'additions' | 'deletions' | 'noise'> & { similarity?: number })[]
  numstat: Map<string, NumstatEntry>
  /** numstat with whitespace and blank lines ignored; files that only changed whitespace are absent. */
  numstatNoWhitespace: Map<string, NumstatEntry>
  linguistGenerated: Set<string>
  rules?: RepoRules
  moved?: Map<string, MovedStat>
  /** Files whose old and new versions have the same code tokens. */
  sameTokens?: Set<string>
}

export function classify(input: NoiseInput): ChangedFile[] {
  const rules = input.rules ?? EMPTY_RULES
  return input.files.map(({ similarity, ...f }) => {
    const stat = input.numstat.get(f.path)
    const file: ChangedFile = { ...f, additions: stat?.additions ?? null, deletions: stat?.deletions ?? null }
    const noise = (kind: NoiseKind, reason: string): ChangedFile => ({ ...file, noise: { kind, reason } })

    if (rules.review.some((p) => matchGlob(f.path, p))) return file
    const rule = rules.skip.find((r) => matchGlob(f.path, r.path))
    if (rule) return noise('repo-rule', rule.reason)
    if (input.linguistGenerated.has(f.path)) return noise('generated', 'Marked as generated in .gitattributes')
    const gen = generatedReason(f.path)
    if (gen) return noise('generated', gen)

    const binary = stat?.additions === null
    const ws = input.numstatNoWhitespace.get(f.path)
    const changedIgnoringWs = ws ? (ws.additions ?? 1) + (ws.deletions ?? 1) > 0 : false

    if (f.status === 'R') {
      if (similarity === 100) return noise('rename-only', `Renamed from ${f.oldPath}, no content changes`)
      if (!binary && !changedIgnoringWs) return noise('rename-only', `Renamed from ${f.oldPath}, only whitespace changed`)
    }
    if (f.status === 'M' && !binary && !changedIgnoringWs) {
      return noise('formatting-only', 'Only whitespace or blank lines changed')
    }
    if ((f.status === 'M' || f.status === 'R') && input.sameTokens?.has(f.path)) {
      return noise('formatting-only', 'Only formatting changed: the code tokens are the same')
    }
    const mv = input.moved?.get(f.path)
    if (mv && !binary && mv.added + mv.deleted > 0 && mv.right.length === mv.added && mv.left.length === mv.deleted) {
      return noise('moved', `Moved code only (${mv.added + mv.deleted} lines moved within or between files)`)
    }
    return file
  })
}
